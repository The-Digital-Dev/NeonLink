#!/usr/bin/env node
// Writes docs/platforms.md (every built-in platform with its icon, variable and what it takes) and the
// platform catalogue at the bottom of compose.yaml (every platform variable, commented out).
//   node scripts/build_platform_docs.mjs          (write both)
//   node scripts/build_platform_docs.mjs --check  (fail if either is out of date; used by the tests)
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PLATFORMS } from '../app/platforms.mjs';
import { composeEnvironmentText } from '../tests/helpers.mjs';

const file = new URL('../docs/platforms.md', import.meta.url);
const composeFile = new URL('../compose.yaml', import.meta.url);
const byLabel = (a, b) => a.label.localeCompare(b.label, 'en', { sensitivity: 'base' }) || a.key.localeCompare(b.key);
const takes = (p) => (p.scheme === 'mailto' ? 'an e-mail address' : p.scheme === 'tel' || p.scheme === 'sms' ? 'a phone number' : 'a link');

export function platformDocs() {
  const rows = [...PLATFORMS]
    .sort(byLabel)
    .map((p) => `| <img src="../app/public/icons/${p.icon}" width="20" height="20" alt=""> | ${p.label} | \`${p.key}\` | ${takes(p)} |`);
  return `# Supported platforms

NeonLink has **${PLATFORMS.length} built-in platforms**. Set the variable to your link and the button
appears with its icon; add \`<VARIABLE>_TEXT\` for your own label, \`<VARIABLE>_NOTE\` for a second line and
\`<VARIABLE>_ICON\` to swap the icon. For anything not listed, use a custom link
([configuration](configuration.md#links)); a custom link can borrow any icon below by its variable,
for example \`LINK_1_ICON: kofi\` or \`CUSTOM_BUTTON_ICON: LINKED_IN\`.

![Every built-in platform icon with its name](images/platforms.png)

To see every button in each design, open the "all platforms" demo of each theme
(\`make demo\`, then \`dist/demo/<theme>/all-platforms/\`).

| Icon | Platform | Variable | Takes |
| --- | --- | --- | --- |
${rows.join('\n')}

Generated by \`scripts/build_platform_docs.mjs\` from [app/platforms.mjs](../app/platforms.mjs). Icon sources
and licences: [THIRD-PARTY-NOTICES.md](../THIRD-PARTY-NOTICES.md). Platform names and logos are trademarks
of their owners.
`;
}

// The catalogue replaces everything from the "---- Every built-in platform" heading to the END line.
const HEAD = /^ {6}# ---- Every built-in platform.*$/m;
const END = /^ {6}# END platform catalogue\s*$/m;
const placeholder = (p) => (p.scheme === 'mailto' ? '<e-mail address>' : p.scheme === 'tel' || p.scheme === 'sms' ? '<phone number>' : '<link>');
export function composeWithCatalogue(text) {
  const start = HEAD.exec(text), end = END.exec(text);
  if (!start || !end || end.index < start.index) throw new Error('compose.yaml: the platform catalogue markers are missing');
  // A platform switched on inside the catalogue would be lost when the block is regenerated: refuse.
  const inside = text.slice(start.index, end.index).split('\n').filter((l) => /^ {6}[A-Z][A-Z0-9_]*:/.test(l));
  if (inside.length) throw new Error(`compose.yaml: move these switched-on lines above the platform catalogue (it is regenerated): ${inside.map((l) => l.trim().split(':')[0]).join(', ')}`);
  const active = composeEnvironmentText(text.slice(0, start.index));
  const pad = (s, n) => s + ' '.repeat(Math.max(1, n - s.length));
  const title = `      # ---- Every built-in platform (${PLATFORMS.length}) `;
  const lines = [
    title + '-'.repeat(Math.max(3, 96 - title.length)),
    '      # Set a variable to your link and its button appears with the logo. Each one also takes',
    '      # <PLATFORM>_TEXT, <PLATFORM>_NOTE and <PLATFORM>_ICON (see "Links" above). "set above" means the',
    '      # sample already uses it: edit that line above instead of uncommenting this one.',
    '      # BEGIN platform catalogue: generated by scripts/build_platform_docs.mjs from app/platforms.mjs',
    ...[...PLATFORMS].sort(byLabel).map((p) => `      # ${pad(`${p.key}: ${p.key in active ? '(set above)' : placeholder(p)}`, 40)}# ${p.label}`),
    '      # END platform catalogue',
  ];
  return text.slice(0, start.index) + lines.join('\n') + text.slice(end.index + end[0].replace(/\s+$/, '').length);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = platformDocs();
  const compose = readFileSync(composeFile, 'utf8');
  const wantCompose = composeWithCatalogue(compose);
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(file, 'utf8'); } catch {}
    let bad = 0;
    if (have !== want) { console.error('docs/platforms.md is out of date: run node scripts/build_platform_docs.mjs'); bad++; }
    if (compose !== wantCompose) { console.error('compose.yaml platform catalogue is out of date: run node scripts/build_platform_docs.mjs'); bad++; }
    if (bad) process.exit(1);
    console.log('docs/platforms.md and the compose.yaml catalogue are up to date');
  } else {
    writeFileSync(file, want);
    writeFileSync(composeFile, wantCompose);
    console.log(`docs/platforms.md and the compose.yaml catalogue written: ${PLATFORMS.length} platforms`);
  }
}
